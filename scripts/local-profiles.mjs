/** Consecutive days read as a range, as on the site: «شنبه تا چهارشنبه». */
function dayRange(days) {
  const idx = [...new Set(days.map((d) => week.indexOf(d)))].sort((a, b) => a - b);
  const runs = [];
  idx.forEach((i) => (runs.length && runs.at(-1).at(-1) === i - 1 ? runs.at(-1).push(i) : runs.push([i])));
  return runs.map((r) => (r.length > 2 ? `${faDays[week[r[0]]]} تا ${faDays[week[r.at(-1)]]}` : r.map((i) => faDays[week[i]]).join(' و '))).join('، ');
}

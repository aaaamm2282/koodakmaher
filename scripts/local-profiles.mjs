const errors = [];
function check(unit, label, text, max) {
  if (!text) return;
  if (chars(text) > max) errors.push(`${unit}، ${label}: ${chars(text)} نویسه؛ بیشتر از ${max}`);
  for (const [re, why] of banned) if (re.test(text)) errors.push(`${unit}، ${label}: ${why} («${text.match(re)[0]}»)`);
}

